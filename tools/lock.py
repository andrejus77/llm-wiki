"""Regenerate requirements.lock: resolve requirements.txt for the TARGET (Windows, Python 3.11.0 — the oldest 3.11 the
server might have) using wheels only, and pin exactly what pip picked. Then install the lock in the dev venv and run
the tests, so the shipped versions are the tested versions.

    python tools/lock.py [--python 3.11] [--platform win_amd64]
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--python", default="3.11")
    ap.add_argument("--platform", default="win_amd64")
    a = ap.parse_args()
    d = Path(tempfile.mkdtemp(prefix="llmwiki-lock-"))
    pyv = a.python.replace(".", "")
    subprocess.run([sys.executable, "-m", "pip", "download", "--only-binary=:all:", "--platform", a.platform, "--python-version", a.python,
                    "--implementation", "cp", "--abi", f"cp{pyv}", "-r", str(ROOT / "requirements.txt"), "-d", str(d), "-q"], check=True)
    pins = []
    for f in sorted(d.glob("*.whl")):
        name, ver = f.name.split("-")[:2]
        pins.append(f"{name.replace('_', '-')}=={ver}")
    head = f"# Generated by tools/lock.py for {a.platform}, Python {a.python} (wheels only). Do not edit by hand.\n"
    (ROOT / "requirements.lock").write_text(head + "\n".join(pins) + "\n", encoding="utf-8")
    shutil.rmtree(d, ignore_errors=True)
    print(f"requirements.lock: {len(pins)} packages")


if __name__ == "__main__":
    main()
